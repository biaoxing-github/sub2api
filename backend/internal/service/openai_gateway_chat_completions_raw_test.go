func TestForwardAsRawChatCompletions_ForcesStreamUsageUpstreamAndPassesUsageDownstream(t *testing.T) {
	gin.SetMode(gin.TestMode)

	body := []byte(`{"model":"gpt-5.4","messages":[{"role":"user","content":"hello"}],"stream":true}`)
	rec := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(rec)
	c.Request = httptest.NewRequest(http.MethodPost, "/v1/chat/completions", bytes.NewReader(body))
	c.Request.Header.Set("Content-Type", "application/json")

	upstreamBody := strings.Join([]string{
		`data: {"id":"chatcmpl_1","object":"chat.completion.chunk","model":"gpt-5.4","choices":[{"index":0,"delta":{"content":"ok"}}]}`,
		"",
		`data: {"id":"chatcmpl_1","object":"chat.completion.chunk","model":"gpt-5.4","choices":[],"usage":{"prompt_tokens":9,"completion_tokens":4,"total_tokens":13,"prompt_tokens_details":{"cached_tokens":3}}}`,
		"",
		"data: [DONE]",
		"",
	}, "\n")
	upstream := &httpUpstreamRecorder{resp: &http.Response{
		StatusCode: http.StatusOK,
		Header:     http.Header{"Content-Type": []string{"text/event-stream"}, "x-request-id": []string{"rid_raw_usage"}},
		Body:       io.NopCloser(strings.NewReader(upstreamBody)),
	}}

	svc := &OpenAIGatewayService{
		cfg:          rawChatCompletionsTestConfig(),
		httpUpstream: upstream,
	}
	account := rawChatCompletionsTestAccount()

	result, err := svc.forwardAsRawChatCompletions(context.Background(), c, account, body, "")
	require.NoError(t, err)
	require.NotNil(t, result)
	require.Equal(t, 9, result.Usage.InputTokens)
	require.Equal(t, 4, result.Usage.OutputTokens)
	require.Equal(t, 3, result.Usage.CacheReadInputTokens)
	require.NotNil(t, upstream.lastReq)
	require.NoError(t, upstream.lastReq.Context().Err())
	require.Equal(t, codexCLIUserAgent(), upstream.lastReq.Header.Get("User-Agent"))
	require.True(t, gjson.GetBytes(upstream.lastBody, "stream_options.include_usage").Bool())
	require.Contains(t, rec.Body.String(), `"usage"`)
	require.Contains(t, rec.Body.String(), "data: [DONE]")
}

// TestForwardAsRawChatCompletions_ServiceTierAfterPolicy 验证出站档位遵循策略，实际响应档位独立记录。
func TestForwardAsRawChatCompletions_ServiceTierAfterPolicy(t *testing.T) {
	gin.SetMode(gin.TestMode)
	for _, stream := range []bool{false, true} {
		for _, filter := range []bool{false, true} {
			name := "buffered"
			if stream {
				name = "stream"
			}
			if filter {
				name += "/filtered"
			} else {
				name += "/passed"
			}
			t.Run(name, func(t *testing.T) {
				body := []byte(`{"model":"gpt-5.4","messages":[{"role":"user","content":"hello"}],"service_tier":"priority","stream":false}`)
				responseBody := `{"service_tier":"default","choices":[{"message":{"role":"assistant","content":"ok"}}],"usage":{"prompt_tokens":2,"completion_tokens":1,"total_tokens":3}}`
				contentType := "application/json"
				if stream {
					body = bytes.Replace(body, []byte(`"stream":false`), []byte(`"stream":true`), 1)
					responseBody = "data: " + responseBody + "\n\ndata: [DONE]\n\n"
					contentType = "text/event-stream"
				}
				rec := httptest.NewRecorder()
				c, _ := gin.CreateTestContext(rec)
				c.Request = httptest.NewRequest(http.MethodPost, "/v1/chat/completions", bytes.NewReader(body))
				upstream := &httpUpstreamRecorder{resp: &http.Response{
					StatusCode: http.StatusOK,
					Header:     http.Header{"Content-Type": []string{contentType}},
					Body:       io.NopCloser(strings.NewReader(responseBody)),
				}}
				svc := &OpenAIGatewayService{cfg: rawChatCompletionsTestConfig(), httpUpstream: upstream}
				if filter {
					svc.settingService = newOpenAIGatewayServiceWithSettings(t, openAIFastFilterPriorityPolicy()).settingService
				}
				result, err := svc.forwardAsRawChatCompletions(context.Background(), c, rawChatCompletionsTestAccount(), body, "")
				require.NoError(t, err)
				require.NotNil(t, result)
				if filter {
					require.False(t, gjson.GetBytes(upstream.lastBody, "service_tier").Exists())
					require.Nil(t, result.ServiceTier)
				} else {
					require.Equal(t, "priority", gjson.GetBytes(upstream.lastBody, "service_tier").String())
					require.NotNil(t, result.ServiceTier)
					require.Equal(t, "priority", *result.ServiceTier)
				}
				require.Equal(t, "default", result.UpstreamResponseServiceTier)
				require.Empty(t, result.UpstreamResponseModel)
			})
		}
	}
}

